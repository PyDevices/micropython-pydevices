// ulab for the GIGA with the Display Shield, set through ULAB_CONFIG_FILE
// (mpconfigvariant.mk), so that Bluetooth fits beside LVGL, audiodsp and the
// USB host. It keeps what audioinstruments, Synth Station and displaydev
// call: array creation, frombuffer, clip, min and max, argmin and argmax,
// sum, the elementwise maths with out=, and numpy.random's Generator, with
// every ndarray operator and method. Arrays have one dimension, which is
// what an audio block is.
//
// Left out, about 74 KB in all: two-dimensional arrays, complex numbers,
// scipy, fft, linalg, ulab.utils, load and save, sorting, polynomials,
// convolution, interpolation, bitwise functions, vectorize and the rarer
// array functions below. A program that needs them wants a GIGA build
// without Bluetooth, or a board with more flash.

